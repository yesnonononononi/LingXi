-- ============================================================================
-- 手工迁移（非 Flyway 自动执行）：字段注释校正 —— email.workflow_execution_id 语义提升为「协作根会话 ID」
-- ----------------------------------------------------------------------------
-- 背景：委派收敛为单一异步协作模式后，邮箱业务键由「协作根执行 ID」提升为「协作根会话 ID」，
--       使「停止根执行后迟到的邮件」能在下一次 beginRoot 时被 AgenticLoopInterceptor 消费
--       （否则邮件会永久停在 PENDING：旧的根执行 id 再也不会被消费）。
--
-- 本脚本只改列注释，不改列名、不改结构类型、不改唯一索引 —— 列名 workflow_execution_id 保持
-- 历史命名不动，仅让注释与新语义对齐；新库由 init.sql 直接建成正确注释，无需执行本脚本。
--
-- 历史数据说明：
--   * 改造前已存在的 email 行，其 workflow_execution_id 存的是「旧根执行 id」，不再会被新链路
--     消费（新链路按根会话 id 查箱）。历史 PENDING 行按「旧键不再被消费」处理，不单独清库；
--     若需清理可另行手工执行（不在本脚本范围内，避免误删仍需保留的消息）。
--   * 无需回填：新链路对新会话/新执行自然按根会话 id 建箱；同一根会话的各轮执行共享同一把键。
--
-- 适用：既有 MySQL 库（内网手动执行一次即可，可重复执行，幂等）。
-- ============================================================================

ALTER TABLE email
    MODIFY COLUMN workflow_execution_id BIGINT NOT NULL
        COMMENT '协作根会话 ID：根执行取自身会话，子执行取 ROOT_SESSION_ID；同一根会话的各轮执行共享同一把邮箱键（列名保持历史命名）';
