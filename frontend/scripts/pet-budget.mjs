/**
 * 桌宠**体积预算的唯一真源**。
 *
 * <p><b>为什么必须只有一个地方定义（这条不是洁癖，是踩出来的）：</b>在本模块出现之前，
 * 同一个"pose 运行资产总量上限"在仓库里有两个值——</p>
 * <ul>
 *   <li>发布侧（`check-pet-not-shipped.mjs`）自裁决 **D-02** 起就是 **8 MiB**；</li>
 *   <li>构建/门禁侧（`build-pet-poses.mjs`）却一直是 **6 MiB**，而且它注释里那句
 *       "切片后每片 ≤ 2 MiB"已经被**切片 2 的 5.15 MiB 实测证伪**。</li>
 * </ul>
 * <p>两个数字并存、且没有任何一条门禁把它们拉到一起比对 = **漂移**，不是"两道闸门各有口径"。
 * 漂移的后果是真正危险的：构建侧说"超了"，发布侧说"没超"，谁红谁不红取决于你跑了哪条命令，
 * 而用户看到的是**打进安装包的那一份**。所以这里只留一个值，两边都 `import`。</p>
 *
 * <p><b>8 MiB 只对应"pose 运行资产进包总量"这一件事。</b>它不是"整个 live2d 目录的上限"，
 * 也不是"任意美术资产的上限"，更不是"可以随手调大的旋钮"。层、脸片、母版各有自己的口径
 * （见 `build-pet-layers.mjs` 的 `LAYERS_TOTAL_BUDGET`、`docs/assets/desktop-pet/**` 的
 * `tools/check-*.mjs`），不许互相借用。</p>
 *
 * <h2>分层规则（预算按资产类分层，一层一个真源）</h2>
 * <ul>
 *   <li>现在有 **`POSE_TOTAL_MAX_BYTES`**（pose 运行资产总量）、
 *       **`FRAME_2X_MAX_BYTES`**（单帧 @2x 编码上限）与
 *       **`SEQUENCE_TOTAL_MAX_BYTES`**（sequence 编排运行资产总量，T05/B1 起）；</li>
 *   <li>新增分层预算**必须随它的消费者（门禁/构建）一起加**，一次提交里同时出现
 *       "定义 + 读它的断言"（`SEQUENCE_TOTAL_MAX_BYTES` 就是按这条落的：定义在本文件，
 *       消费方是 `scripts/check-pet-sequences.mjs` 的 G-S3）；</li>
 *   <li><b>严禁添加"定义了但没有任何门禁读"的常量。</b>本仓已有前科：
 *       `isPlayable` 的"缺锚即不可播"曾是一项**恒成立的空门**（归一化器会自动补镜像锚），
 *       空门比没有门更糟——它让人以为有守卫。判断标准只有一条：
 *       <b>把常量改成一个立刻会崩的值，必须有人变红；否则它就不是守卫。</b></li>
 * </ul>
 *
 * @module scripts/pet-budget
 */

/**
 * 单帧 `@2x` 体积上限（400 KiB）。
 *
 * <p>取值依据：按分层件面积外推 172 KiB 的 **2.3 倍留白**。超了不会静默——
 * `transcodeLayer` 的自动降级旁路会把它转成有损（字节更少、体积断言照样绿），
 * 所以 G-P8 另有一条"每帧必须是 `webp-lossless`"的守卫盯着那个旁路。</p>
 */
export const FRAME_2X_MAX_BYTES = 400 * 1024;

/**
 * 全 pose 运行资产体积上限（8 MiB = 8388608 B）。
 *
 * <p>依据（写进注释是为了不让将来的人把它"清理"成一句空话）：发布侧
 * `check-pet-not-shipped.mjs` 自裁决 **D-02** 起就一直按 8 MiB 拦"进包总量"；
 * 构建侧原先的 6 MiB 才是那个一直漂着的值——它注释里"切片后每片 ≤ 2 MiB"的口径，
 * 已被切片 2 实测的 5.15 MiB **证伪**。本模块把两边统一到 D-02 的 8 MiB。</p>
 *
 * <p>改这个值必须有新的算账依据（例如美术提高分辨率、或切片 3 的实测增量表），
 * 并按 D-02 重新裁决；只"因为现在超了"就抬上限是禁止的。</p>
 */
export const POSE_TOTAL_MAX_BYTES = 8 * 1024 * 1024;

/**
 * 全 sequence（编排）运行资产体积上限（2 MiB = 2097152 B）。
 *
 * <p><b>为什么 play 必须有自己的口袋：</b>pose 的 8 MiB 是"身体形态逐帧像素"的账，编排资产
 * （伙伴帧 / 手掌层）是另一类东西。若两者共用一处上限，play 切片一落地就会去啃 pose 的余量，
 * 那时谁也说不清"红了是 pose 胖了还是 play 长出来了"（设计 §7.6）。</p>
 *
 * <p><b>取值依据（实测，不是拍脑袋）：</b>`cloud_react` 竖切（T05/B1，1 场景 8 步 3.18 s）
 * 实测运行资产仅 **+5,146 B**；`play_cloud` 全量（双角色 + 手掌层 + 5 个新帧）实测约
 * **407,557 B**。取 2 MiB ⇒ 相对全量 play 仍留约 **5 倍余量**，够后续 `play_cloud` 变体长出来。</p>
 *
 * <p><b>改这个数只有一条合法路径：随实测增量表调整</b>（新场景交付时把实测字节数补进本注释，
 * 再按新的总量重新裁决）。"因为现在超了"就抬上限，和把门禁删掉没有区别。</p>
 */
export const SEQUENCE_TOTAL_MAX_BYTES = 2 * 1024 * 1024;
