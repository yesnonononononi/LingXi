-- response_order：本轮模型调用在一轮内的序号（0 基），只挂在 AI 行。
--
-- 用途：Block 装配的两层顺序里，「响应顺序」这一层靠它。同一轮里模型可以多轮
-- 「思考 → 调工具 → 再思考」，若干 AI 行共享同一 turn_id；没有这个序号就只能按
-- 消息主键（插入顺序）排，而插入顺序与模型调用顺序在并发/补写场景下并不等价。
--
-- 旧数据为 NULL：表示序号未知（本次改造之前落库的 AI 行）。展示层按「未知」降级，
-- 不猜一个 0 出来 —— 猜出来的 0 会让旧行全都排到新一轮前面。
ALTER TABLE session_message ADD COLUMN response_order INT NULL;
