-- V13：file_record 的「同文件同版本」唯一性
--
-- 为什么要有：version 由 put 用 SELECT MAX(version)+1 现场分配，那个「先查后插」天然有
--   竞争窗口。没有库里这条唯一约束时，撞车的后果是**同一文件出现两条同版本记录**——
--   不报错、不显眼，只是重放链上多出一段谁也不认识的顺序。
--   加了约束，最坏情况变成一次显式失败，问题当场可见。
--
-- 为什么是这三列：执行内、同一文件、版本号递增是 records 模块对外承诺的语义
--   （「本轮首次修改保留基线，后续置空」依赖它就是靠这份顺序读出来的）。
--   唯一性只在「同一执行 + 同一文件 + 同一版本」这一组上才成立，放宽任何一列都会削弱它。
--
-- 为什么不改 V12：V12 已经在用户库里跑过了，改它等于对已迁移的库不生效；结构演进一律追加。
-- ------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS ux_file_record_file_version
    ON file_record (execution_id, file_path, version);
