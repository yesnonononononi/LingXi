-- ------------------------------------------------------------
-- V12：文件编辑记录（file_record）落库
--
-- 为什么落库：这份记录此前只活在后端进程内存里（ConcurrentHashMap），**后端一重启就没了**，
--   于是历史会话的「本轮改动文件清单」重建不出来 —— 界面上表现为卡片凭空消失，
--   而磁盘上的文件明明改过。记录必须跨进程存活才谈得上可观测。
--
-- 为什么基线不在这张表里：基线是「本轮第一次改该文件之前的全文」，是这里唯一的超大字段。
--   落 CLOB 等于每次工具收尾都碰一次大 LOB 写放大，还会把大文本压进库文件；
--   因此基线写进数据目录的文件系统（<数据目录>/file-records/<execution_id>/<id>.baseline），
--   本表只存**绝对路径引用**（baseline_path）。NULL = 本轮开始时文件不存在（新建）或基线已过期回收。
--   差异（diff）本身小得多，留在 CLOB 里，只读一条记录时不会连带读基线。
--
-- 为什么主键是自增 seq 而不是 id：**顺序是契约的一部分**。差异重放要求按写入顺序叠加，
--   而记录标识是 UUID（无序）。seq 由库按插入顺序发放，listByExecution 直接 ORDER BY seq，
--   顺序责任留在存储层，服务层不需要也不允许重排。id 另有唯一索引，业务标识仍然稳定。
--
-- 15 天回收：create_at 有索引，清理入口按它整条回收（行 + 基线文件），避免表只增不减。
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS file_record (
    seq           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id            VARCHAR(64)   NOT NULL,
    execution_id  VARCHAR(64)   NOT NULL,
    turn_id       VARCHAR(64)   NULL,
    version       INTEGER       NOT NULL,
    file_path     VARCHAR(1024) NOT NULL,
    -- 基线文件的绝对路径；NULL = 新建文件（无基线）或基线已被过期回收。
    baseline_path VARCHAR(1024) NULL,
    -- 这一次编辑的 unified diff；CLOB，避免 H2 的 TEXT 变成十亿字符 VARCHAR。
    diff          CLOB          NULL,
    plus_lines    INTEGER       NOT NULL DEFAULT 0,
    minus_lines   INTEGER       NOT NULL DEFAULT 0,
    create_at     TIMESTAMP(3)  NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_file_record_id ON file_record (id);

-- 按执行取记录：ORDER BY seq 走这条索引，插入顺序即重放顺序。
CREATE INDEX IF NOT EXISTS idx_file_record_execution ON file_record (execution_id, seq);

-- 「本轮是否已改过这个文件」与同文件版本递增都要按这三个列定位。
CREATE INDEX IF NOT EXISTS idx_file_record_turn_file ON file_record (execution_id, turn_id, file_path);

-- 过期回收按时间扫。
CREATE INDEX IF NOT EXISTS idx_file_record_create_at ON file_record (create_at);
