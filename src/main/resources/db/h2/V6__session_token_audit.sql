-- ------------------------------------------------------------
-- V6：会话级 Token 审计快照（侧边栏「上下文构成」的数据源）
--
-- 为什么是「头 + 明细行」两张表：
--   1. 工具名是动态集合（MCP / Skill / 任意普通工具），写成列就要随工具增减改 DDL；
--      写成 JSON CLOB 又无法用 SQL 求和校验，还会在 H2 上重新引入大字段读放大。
--      工具名放进行里（tool_name 是值），结构就固定了。
--   2. 头表只放「不可由明细推导」的量（总量、分项合计、请求开销、采集时间、状态）；
--      任何能被明细求和算出来的数都不落库 —— 一份事实只有一个存放点。
--
-- 为什么主键是 session_id：一个会话只保留「最近一次成功采集」，天然是 upsert 键，
--   与 session_context（PK = session_id）同一先例，不需要额外雪花 id。
--
-- 为什么明细用自增主键：每次采集「删旧行 + 插新行」，明细行不需要跨实例唯一标识；
--   session / execution / mcp 等 PO 早已在用 IdType.AUTO。
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS session_token_audit (
    session_id              BIGINT NOT NULL PRIMARY KEY,
    -- 产出这份快照的执行；归属解析失败时可能为 NULL（此时只落库、不广播）。
    execution_id            BIGINT NULL,
    -- COLLECTED / FAILED：持久层只承认这两种事实；CAPTURING 是查询时派生出来的展示态。
    audit_state             VARCHAR(16) NOT NULL DEFAULT 'COLLECTED',
    -- 框架口径的「模型输入总量」：消息 + 工具定义 + 请求框架（与 CONTEXT_UPDATE 同源）。
    total_tokens            INTEGER NULL,
    max_tokens              INTEGER NULL,
    -- 四类分项之和（去重叠口径）。与 total_tokens 的差由下一列解释。
    messages_tokens         INTEGER NULL,
    request_overhead_tokens INTEGER NULL,
    -- 工具调用参数 token：已计入 AI 项，仅供说明，不参与任何求和。
    overlap_tokens          INTEGER NULL,
    captured_at             TIMESTAMP(3) NULL,
    fail_reason             VARCHAR(512) NULL,
    create_time             TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time             TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_session_token_audit_execution ON session_token_audit (execution_id);

CREATE TABLE IF NOT EXISTS session_token_audit_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id       BIGINT NOT NULL,
    -- 1 = 消息类（4 行）、2 = 工具分组、3 = 普通工具明细（按工具名）。
    item_level       TINYINT NOT NULL,
    category         VARCHAR(16) NOT NULL,
    group_kind       VARCHAR(16) NULL,
    tool_name        VARCHAR(128) NULL,
    -- 该聚合项覆盖的调用条数（前端「N 项」徽标）；MCP / Skill 分组也填。
    call_count       INTEGER NOT NULL DEFAULT 0,
    -- 框架原值：包含 argument_tokens。
    total_tokens     INTEGER NOT NULL DEFAULT 0,
    argument_tokens  INTEGER NOT NULL DEFAULT 0,
    output_tokens    INTEGER NOT NULL DEFAULT 0,
    sort_order       INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_session_token_audit_item_owner
    ON session_token_audit_item (session_id, item_level, sort_order);
