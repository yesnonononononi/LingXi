-- 恢复请求的来源：决定消费端复检用哪一套门禁口径（人工决策 vs 自动唤醒）。
--
-- 为什么必须落库：来源原先只存在内存参数里。进程在「请求已提交、派发还没跑完」时崩溃，
-- 重启重投会把来源退化成自动唤醒 —— 人工批准随即被 AUTO_ROUNDS 上限或 USER_PAUSED 判掉，
-- 请求被静默作废，而当时回执说的是「已受理」。恢复队列存的是「请求」，缺了决定它能否
-- 恢复的那一半信息，就不是一条完整请求。
--
-- 可空是刻意的：升级前遗留的行没有来源，NULL 由应用层按「自动唤醒」的保守口径处理
-- （宁可多查一道门禁，也不替人做决定）。写入方永远写非空值。
ALTER TABLE execution_resume_task ADD COLUMN IF NOT EXISTS trigger_type VARCHAR(32) NULL;
