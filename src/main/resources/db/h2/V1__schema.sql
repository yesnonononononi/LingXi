-- =====================================================================
-- LingXi H2 基线建库脚本 V1（H2 侧唯一 DDL 真源）
--
-- 真源是「当前 SQLite 的 V1 + V2 脚本」加各持久化 PO 的实际字段；
-- H2 库永远从空开始（迁移工具灌数据），所以这里只有一份完整基线，没有补列式迁移。
-- 将来加版本时新增 V2__xxx.sql 即可，版本表 schema_version 已经预留。
--
-- 写法约束（全部由 H2 2.5.252 真实文件库实测确认，勿凭印象改）：
--   1. 全部 IF NOT EXISTS：脚本必须可重入。H2 的 DDL 会隐式提交，半途失败回滚不掉，
--      重入是唯一的补齐手段。
--   2. 没有 SQL 触发器：H2 只支持 Java 类触发器（AS 'java.class'），没有 SQL 触发器体。
--      SQLite 侧 *_touch 触发器的语义（UPDATE 未显式改时间列时自动刷新为当前时间）由
--      update_time/updated_at/update_at 列上的 ON UPDATE CURRENT_TIMESTAMP 承担 —— 实测
--      2.5.252 支持该子句，且「显式赋值优先、未赋值才自动刷新」与触发器的 WHEN NEW IS OLD 等价。
--      checklist / checklist_step 在 SQLite 侧本来就没有触发器（update_at 由仓储显式写），
--      这里保持一致，不给它们加 ON UPDATE。
--   3. 无 AUTOINCREMENT：自增统一 BIGINT GENERATED BY DEFAULT AS IDENTITY
--      （允许显式插入 id，迁移工具据此搬运历史主键，再 ALTER ... RESTART WITH 续号）。
--   4. 无 VIRTUAL 关键字：H2 的生成列不能写 VIRTUAL；去掉后同样可建唯一索引并拒绝第二条 ACTIVE。
--   5. 标识符一律不加引号（H2 折叠为大写）；不得使用 H2 保留字（KEY / VALUE / YEAR / USER / ROW 等）。
--   6. 大文本一律 CLOB：H2 的 TEXT 是 CHARACTER VARYING(1000000000)，即 10 亿字符的
--      VARCHAR，正是旧 OOM 事故的成因；只有 CLOB 才是真正的字符大对象。
--   7. 时间列一律 TIMESTAMP(3)（毫秒）；连接固定 SET TIME ZONE 'UTC'，所以列里存的是
--      UTC 墙钟，与 SQLite 的 'yyyy-MM-dd HH:mm:ss.SSS' UTC 文本语义等价。
--   8. 小数一律给精度：裸 NUMERIC 在 H2 是 DECIMAL(100000,0)，0.62 会变成 1。
--      context_ratio 用 DOUBLE PRECISION：它是 0~1 的占比，真实数据里小数位远超 4 位
--      （实测样本 0.09512015503875969），NUMERIC(6,4) 会把它截成 0.0951 —— 迁移工具按
--      「不允许静默丢精度」判定指纹不一致并拒绝，等于让真实用户数据迁不过来。
--      DOUBLE PRECISION 不做定点舍入，与 SQLite 的 NUMERIC 存储语义等价。
--   9. 脚本里不得出现 DROP / TRUNCATE（含它的脚本会被初始化器直接拒绝）。
-- =====================================================================

-- ------------------------------------------------------------
-- 1. MCP 服务配置
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mcp (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(255) NOT NULL,
    description            VARCHAR(2048) NULL,
    transport              VARCHAR(64)  NOT NULL DEFAULT 'streamable-http',
    url                    VARCHAR(1024) NULL,
    headers                VARCHAR(8192) NULL,
    command                VARCHAR(4096) NULL,
    env                    VARCHAR(8192) NULL,
    initialization_timeout BIGINT NULL,
    execution_timeout      BIGINT NULL,
    protocol_version       VARCHAR(64) NULL,
    auto_health_check      INTEGER NULL,
    health_check_interval  BIGINT NULL,
    reconnect_interval     BIGINT NULL,
    max_output             INTEGER NULL,
    status                 INTEGER NOT NULL DEFAULT 1,
    create_time            TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time            TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_mcp_name ON mcp (name);
CREATE INDEX IF NOT EXISTS idx_mcp_status ON mcp (status);

-- ------------------------------------------------------------
-- 2. 模型提供商预设（运行期真源是 providers.json，本表只承担首次导入）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS provider_config (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    icon        VARCHAR(4096) NULL,
    base_url    VARCHAR(1024) NULL,
    api_key     VARCHAR(1024) NULL,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    create_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_provider_config_name ON provider_config (name);

-- ------------------------------------------------------------
-- 3. 模型配置（运行期真源是 models.json）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS model_config (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name         VARCHAR(255) NOT NULL,
    base_url           VARCHAR(1024) NOT NULL,
    api_key            VARCHAR(1024) NULL,
    provider           VARCHAR(255) NULL,
    provider_config_id BIGINT NULL,
    vision             INTEGER NOT NULL DEFAULT 0,
    use_provider       INTEGER NOT NULL DEFAULT 0,
    create_time        TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time        TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_model_name_base_url ON model_config (model_name, base_url);
CREATE INDEX IF NOT EXISTS idx_model_config_provider ON model_config (provider_config_id);

-- ------------------------------------------------------------
-- 4. 工作空间
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS workspace (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL DEFAULT '工作空间',
    host_dir    VARCHAR(1024) NOT NULL,
    create_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- 5. 会话（一条记录 = 一个会话聚合）
--    context_ratio 是 0~1 的占比：用 DOUBLE PRECISION，不用裸 NUMERIC（会退化成整数），
--    也不用 NUMERIC(6,4)（真实数据小数位更多，定点会截断、迁移指纹随之不一致）。
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS session (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_read             INTEGER NOT NULL DEFAULT 1,
    history_revision    BIGINT NOT NULL DEFAULT 1,
    version             BIGINT NOT NULL DEFAULT 1,
    root_session_id     BIGINT NOT NULL DEFAULT 0,
    agent_id            BIGINT NULL,
    name                VARCHAR(255) NOT NULL DEFAULT '新对话',
    workspace_id        BIGINT NULL,
    team_id             BIGINT NULL,
    context_token_count BIGINT NULL,
    context_max_tokens  INTEGER NULL,
    context_ratio       DOUBLE PRECISION NULL,
    create_time         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_workspace_id ON session (workspace_id);
CREATE INDEX IF NOT EXISTS idx_create_time ON session (create_time);
CREATE INDEX IF NOT EXISTS idx_root_session_id ON session (root_session_id);
CREATE INDEX IF NOT EXISTS idx_root_agent ON session (root_session_id, agent_id);

-- ------------------------------------------------------------
-- 6. 会话消息（List<Message> 拆表存储；卡片载荷在 tool_call）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS session_message (
    id                BIGINT PRIMARY KEY,
    response_id       VARCHAR(128) NULL,
    resume_request_id VARCHAR(128) NULL,
    session_id        BIGINT NOT NULL,
    turn_id           BIGINT NULL,
    type              VARCHAR(64) NOT NULL,
    content           CLOB NOT NULL,
    create_time       TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_session_resume_request ON session_message (session_id, resume_request_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_session_response_id ON session_message (session_id, response_id);
CREATE INDEX IF NOT EXISTS idx_session_msg ON session_message (session_id, id);

-- 模型推理上下文快照（允许压缩替换）；content 是整段上下文，历史样本超过 1000 万字符
CREATE TABLE IF NOT EXISTS session_context (
    session_id  BIGINT PRIMARY KEY,
    content     CLOB NOT NULL,
    version     BIGINT NOT NULL DEFAULT 1,
    create_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- 7. 通用配置（单例行，主键固定 1；CHECK 在 H2 实测生效，违反抛 23513）
