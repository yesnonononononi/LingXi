    max_tokens              INTEGER DEFAULT NULL,
    reasoning_effort        VARCHAR(32) DEFAULT NULL,
    render_theme            VARCHAR(64) NOT NULL DEFAULT 'LIGHT',
    data_dir                VARCHAR(1024) DEFAULT NULL,
    skill_dir               VARCHAR(1024) DEFAULT NULL,
    team_size               INTEGER DEFAULT NULL,
    compact_model_id        BIGINT DEFAULT NULL,
    font_scale              VARCHAR(32) DEFAULT NULL,
    status                  INTEGER DEFAULT 1,
    create_time             TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time             TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT chk_user_configs_singleton CHECK (id = 1)
);

