    content             CLOB NULL,
    raw_input           CLOB NULL,
    raw_output          CLOB NULL,
    meta_data           CLOB NULL,
    decision_command_id VARCHAR(128) NULL,
    decision_digest     VARCHAR(128) NULL,
    version             BIGINT NOT NULL DEFAULT 1,
    created_at          TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
